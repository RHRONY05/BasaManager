#!/usr/bin/env node
// Capture the public pages (landing, login, signup) from the RUNNING app into artboard sources, so the design
// folder shows exactly what is built. These three pages were redesigned in code (2026-11-10); their artboards
// are snapshots, not hand-written HTML.
//
//   1. start the app (pnpm dev, or at least the web + api dev servers)
//   2. node .agent/design/tools/snapshot.mjs [--base http://localhost:5173]
//   3. python .agent/design/tools/build.py
//
// Writes tools/src/{desktop,mobile}/0{1,2,3}-*.html (shell "snapshot") and ../app.css (the app's CSS, minus the
// self-hosted @font-face rules; the artboards get the same fonts from Google Fonts via ../tokens.css).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = path.dirname(fileURLToPath(import.meta.url));
const designDir = path.resolve(here, '..');
const repo = path.resolve(designDir, '..', '..');
const { chromium } = createRequire(path.join(repo, 'package.json'))('@playwright/test');

const args = process.argv.slice(2);
const base = (args[args.indexOf('--base') + 1] && args.includes('--base') ? args[args.indexOf('--base') + 1] : 'http://localhost:5173').replace(/\/$/, '');

const PAGES = [
  { route: '/', file: '01-landing.html', d: 'D01 · Landing', m: 'M01 · Landing' },
  { route: '/login', file: '02-login.html', d: 'D02 · Login', m: 'M02 · Login' },
  { route: '/signup', file: '03-signup.html', d: 'D03 · Signup', m: 'M03 · Signup' },
];
const DEVICES = [
  { dir: 'desktop', key: 'd', width: 1440, height: 900 },
  { dir: 'mobile', key: 'm', width: 390, height: 844 },
];

const browser = await chromium.launch();
let css = '';
for (const device of DEVICES) {
  for (const p of PAGES) {
    const page = await browser.newPage({ viewport: { width: device.width, height: device.height }, colorScheme: 'light' });
    await page.goto(base + p.route, { waitUntil: 'networkidle' });
    await page.waitForTimeout(600);
    const { html, sheet } = await page.evaluate(() => {
      const root = document.getElementById('root').cloneNode(true);
      root.querySelectorAll('script, [data-progress-bar]').forEach((n) => n.remove());
      // links become in-gallery hashes, like the other artboards
      root.querySelectorAll('a[href^="/"]').forEach((a) => a.setAttribute('href', '#' + a.getAttribute('href')));
      root.querySelectorAll('input').forEach((i) => i.removeAttribute('value'));
      const rules = [];
      for (const s of document.styleSheets) {
        let list;
        try { list = s.cssRules; } catch { continue; }
        for (const r of list) if (!(r instanceof CSSFontFaceRule)) rules.push(r.cssText);
      }
      return { html: root.outerHTML, sheet: rules.join('\n') };
    });
    if (!css) css = sheet;
    const title = p[device.key];
    const src = `<!--meta {"title": "${title}", "shell": "snapshot", "source": "${p.route}"} -->\n<!-- Captured from the running app by tools/snapshot.mjs. Re-capture; don't hand-edit. -->\n${html}\n`;
    fs.writeFileSync(path.join(here, 'src', device.dir, p.file), src, 'utf8');
    console.log(`captured ${device.dir}/${p.file}`);
    await page.close();
  }
}
await browser.close();

fs.writeFileSync(
  path.join(designDir, 'app.css'),
  `/* GENERATED by tools/snapshot.mjs from the running app (Tailwind output + tokens + components).\n   Used only by the snapshot artboards (landing, login, signup). Do not edit by hand. */\n${css}\n`,
  'utf8',
);
console.log('wrote app.css');
